def directly_addresses_jimbo(message):
    return re.search(r"\bjimbo\b", message, flags=re.IGNORECASE) is not None


def loosely_refers_to_jimbo(message):
    lowered = message.lower()
    target = "jimbo"
    n = len(target)
    for i in range(len(lowered) - n + 1):
        chunk = lowered[i:i + n]
        if sum(c1 != c2 for c1, c2 in zip(chunk, target)) <= 1:
            return True
    return False


def _is_recognized_classification(raw):
    line = (raw or "").strip()
    if line in ("SKIP", "NONE", "PLATFORMS", "PLANETS"):
        return True
    if line.upper().startswith("NONE"):
        return True
    if line.startswith("/"):
        return True
    return any(
        parser is not None
        for parser in (
            parse_logistics_decision(line),
            parse_produce_decision(line),
            parse_tag_decision(line),
            parse_untag_decision(line),
            parse_top_damage_decision(line),
            parse_lookup_decision(line),
            parse_remove_decision(line),
            parse_job_status_decision(line),
        )
    )


def query_player_location(client, username):
    """Read-only RCON: the requesting player's physical position and surface.

    Used so freeform slash-commands can anchor on 'my current location' with
    concrete coordinates instead of indexing the client-only game.player. An
    empty result means the player is offline or unavailable.
    """
    command = (
        "/silent-command local p=game.get_player(%s);"
        "if p and p.connected and p.physical_surface then "
        "rcon.print(p.position.x..','..p.position.y..','..p.physical_surface.name) "
        "else rcon.print('') end" % json.dumps(username)
    )
    try:
        raw = (client.run(command) or "").strip()
    except Exception as e:
        print(f"Location query failed for {username}: {e}", flush=True)
        return ""
    if not raw or raw.startswith("["):
        return ""
    parts = raw.split(",")
    if len(parts) != 3:
        return ""
    try:
        x, y = float(parts[0]), float(parts[1])
    except ValueError:
        return ""
    surf = parts[2]
    return (
        f"{username} is currently at ({x:.1f}, {y:.1f}) on surface "
        f"'{surf}'. If the request locates something relative to the player's "
        "current location, anchor on this position (north is decreasing Y, "
        "south increasing Y, west decreasing X, east increasing X) and use "
        "these concrete coordinates in the /silent-command; game.player is not "
        "available over RCON."
    )


def classify_current_message(username, message, history_text, location_context=""):
    prompt = build_classification_prompt(
        username, message, history_text, location_context=location_context
    )
    raw = ask_ai(prompt).split("\n")[0].strip()
    if raw == "SKIP" and directly_addresses_jimbo(message):
        print(
            "Classifier incorrectly skipped a direct Jimbo message; retrying",
            flush=True,
        )
        retry_prompt = (
            prompt
            + "\n\nYour previous answer was SKIP, but the current message directly "
            "addresses Jimbo. Under the rules above it must be classified as NONE, "
            "a structured request, or an executable slash command. Classify the "
            "current message again with exactly one line."
        )
        raw = ask_ai(retry_prompt).split("\n")[0].strip()
    if not _is_recognized_classification(raw):
        print(
            f"Classifier returned an unrecognized response {raw!r}; retrying",
            flush=True,
        )
        retry_prompt = (
            prompt
            + "\n\nYour previous reply was not a single recognized output. "
            "It contained reasoning or explanation instead of one of the "
            "required forms. Reply with exactly one line: SKIP, NONE, "
            "PLATFORMS, PLANETS, or one of the exact structured command "
            "formats listed above."
        )
        raw = ask_ai(retry_prompt).split("\n")[0].strip()
    return raw


def parse_lookup_decision(raw):
    if not raw.startswith("LOOKUP|"):
        return None
    parts = raw.split("|")
    if len(parts) < 3:
        return None
    class_part = parts[1].strip()
    question = " ".join("|".join(parts[2:]).split())
    if not class_part or not question:
        return None
    if len(question) > lookup_question_max_chars:
        return None
    class_names = [name.strip() for name in class_part.split(",") if name.strip()]
    if not 1 <= len(class_names) <= lookup_max_classes:
        return None
    for name in class_names:
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]{0,63}", name):
            return None
    return class_names, question


