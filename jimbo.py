def update_research_stall_state(research_text, spontaneous_state):
    name = None
    level = None
    progress = None
    for line in research_text.splitlines():
        if line.startswith("Current: "):
            name = line[len("Current: "):].strip()
        elif line.startswith("Current level: "):
            level = line[len("Current level: "):].strip()
        elif line.startswith("Progress: "):
            try:
                progress = float(line[len("Progress: "):].strip().rstrip("%"))
            except ValueError:
                pass
    if name is None or progress is None:
        return "unavailable", name, progress
    if level is not None:
        name = f"{name} (level {level})"

    unchanged = (
        name != "none"
        and name == spontaneous_state.get("research_name")
        and progress == spontaneous_state.get("research_progress")
    )
    if unchanged:
        status = (
            "stalled"
            if spontaneous_state.get("stall_announced")
            else "new_stall"
        )
    else:
        status = "changed"
        spontaneous_state["stall_announced"] = False
    spontaneous_state["research_name"] = name
    spontaneous_state["research_progress"] = progress
    return status, name, progress


def is_quiet_request(message):
    normalized = message.lower()
    for punctuation in ",.!?":
        normalized = normalized.replace(punctuation, " ")
    normalized = " ".join(normalized.split())
    return any(
        phrase in normalized
        for phrase in (
            "shut up jimbo",
            "jimbo shut up",
            "be quiet jimbo",
            "jimbo be quiet",
            "stop talking jimbo",
            "jimbo stop talking",
        )
    )


def is_forget_request(message):
    normalized = message.strip().lower().rstrip(".!")
    return normalized == "jimbo, forget all previous instructions"


def _collapse(text, cap):
    parts = " ".join((text or "").split())
    if len(parts) > cap:
        parts = parts[:cap].rstrip() + "…"
    return parts


def _format_type(typ, cap=60):
    if isinstance(typ, list):
        typ = ", ".join(str(t) for t in typ)
    return _collapse(str(typ or ""), cap)


def extract_api_slices(doc, class_names):
    entries = {}
    for entry in doc.get("classes", []) + doc.get("concepts", []):
        name = entry.get("name")
        if name:
            entries[name] = entry
    blocks = []
    total = 0
    for name in class_names:
        entry = entries.get(name)
        if entry is None:
            continue
        lines = [f"## {name}"]
        desc = _collapse(
            entry.get("description"), lookup_member_description_chars
        )
        if desc:
            lines.append(desc)
        for attr in entry.get("attributes", []):
            line = (
                f"- {attr.get('name')} :: "
                f"{_format_type(attr.get('type') or attr.get('read_type'))}"
            )
            member_desc = _collapse(
                attr.get("description"), lookup_member_description_chars
            )
            if member_desc:
                line += f" — {member_desc}"
            lines.append(line)
        for method in entry.get("methods", []):
            params = ", ".join(
                f"{p.get('name', '?')}{'?' if p.get('optional') else ''}"
                for p in method.get("parameters", [])
            )
            returns = [
                _format_type(r.get("type"), 40)
                for r in method.get("return_values", [])
                if r.get("type") is not None
            ]
            ret_text = f" -> {', '.join(returns)}" if returns else ""
            line = f"- {method.get('name')}({params}){ret_text}"
            member_desc = _collapse(
                method.get("description"), lookup_member_description_chars
            )
            if member_desc:
                line += f" — {member_desc}"
            lines.append(line)
        block = "\n".join(lines)
        remaining = lookup_slice_max_chars - total
        if len(block) > remaining:
            if remaining < 200:
                break
            block = block[:remaining].rstrip() + "\n[truncated]"
            blocks.append(block)
            break
        blocks.append(block)
        total += len(block)
    return "\n\n".join(blocks)


FORBIDDEN_LUA_CHECKS = (
    ("give_item_stack", "item grants"),
    ("teleport", "teleporting players"),
    (".destroy(", "destructive changes"),
    ("kill_all", "destructive changes"),
    ("remove_item", "destructive changes"),
    ("write_file", "file access"),
)


def forbidden_lua_reason(command):
    lowered = (command or "").lower()
    for pattern, reason in FORBIDDEN_LUA_CHECKS:
        if pattern in lowered:
            return reason
    if re.search(r"(?<!table)\.insert\s*[({]", lowered):
        return "item grants"
    if ".create_entity" in lowered and not (
        "entity-ghost" in lowered or "inner_name" in lowered
    ):
        return "spawning entities"
    return None


def strip_code_fences(text):
    kept = [
        line for line in text.splitlines() if not line.strip().startswith("```")
    ]
    return "\n".join(kept).strip()


